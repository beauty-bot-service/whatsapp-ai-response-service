CREATE TABLE IF NOT EXISTS CONVERSATION_PROMOTION_DELIVERIES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONVERSATION_SESSION_ID BIGINT NOT NULL,
    PROMOTION_ID BIGINT NOT NULL,
    PROMOTION_CODE VARCHAR(50) NOT NULL,
    DELIVERED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT FK_PROMOTION_DELIVERIES_SESSION
        FOREIGN KEY (CONVERSATION_SESSION_ID) REFERENCES CONVERSATION_SESSIONS (ID),
    CONSTRAINT FK_PROMOTION_DELIVERIES_PROMOTION
        FOREIGN KEY (PROMOTION_ID) REFERENCES PROMOTIONS (ID),
    CONSTRAINT UK_PROMOTION_DELIVERIES_SESSION_PROMOTION
        UNIQUE (CONVERSATION_SESSION_ID, PROMOTION_ID)
);

CREATE INDEX IF NOT EXISTS IDX_PROMOTION_DELIVERIES_SESSION
    ON CONVERSATION_PROMOTION_DELIVERIES (CONVERSATION_SESSION_ID, DELIVERED_AT);

CREATE INDEX IF NOT EXISTS IDX_PROMOTION_DELIVERIES_PROMOTION
    ON CONVERSATION_PROMOTION_DELIVERIES (PROMOTION_ID, DELIVERED_AT);
