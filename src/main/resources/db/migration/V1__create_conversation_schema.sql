CREATE TABLE IF NOT EXISTS CONVERSATION_SESSIONS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PHONE_NUMBER VARCHAR(32) NOT NULL,
    STATE VARCHAR(32) NOT NULL,
    CUSTOMER_NAME VARCHAR(120),
    TREATMENT_INTEREST VARCHAR(120),
    FIRST_TIME BOOLEAN,
    PREFERRED_TIME VARCHAR(120),
    CONTACT_PREFERENCE VARCHAR(32),
    WAITING_FOR_FIELD VARCHAR(32),
    REQUIRES_HUMAN BOOLEAN NOT NULL,
    SUMMARY_FOR_HUMAN TEXT,
    HUMAN_NOTIFIED_AT TIMESTAMP,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS IDX_CONVERSATION_SESSIONS_PHONE ON CONVERSATION_SESSIONS (PHONE_NUMBER);
CREATE INDEX IF NOT EXISTS IDX_CONVERSATION_SESSIONS_PHONE_UPDATED_AT ON CONVERSATION_SESSIONS (PHONE_NUMBER, UPDATED_AT);
CREATE INDEX IF NOT EXISTS IDX_CONVERSATION_SESSIONS_STATE_UPDATED_AT ON CONVERSATION_SESSIONS (STATE, UPDATED_AT);

CREATE TABLE IF NOT EXISTS CONVERSATION_MESSAGES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SESSION_ID BIGINT NOT NULL,
    PHONE_NUMBER VARCHAR(32) NOT NULL,
    DIRECTION VARCHAR(16) NOT NULL,
    SENDER_TYPE VARCHAR(16) NOT NULL,
    CHANNEL VARCHAR(32),
    EXTERNAL_MESSAGE_ID VARCHAR(120),
    CONTENT TEXT NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT FK_CONVERSATION_MESSAGES_SESSION FOREIGN KEY (SESSION_ID) REFERENCES CONVERSATION_SESSIONS (ID)
);

CREATE INDEX IF NOT EXISTS IDX_CONVERSATION_MESSAGES_SESSION_CREATED_AT ON CONVERSATION_MESSAGES (SESSION_ID, CREATED_AT);
CREATE INDEX IF NOT EXISTS IDX_CONVERSATION_MESSAGES_PHONE_CREATED_AT ON CONVERSATION_MESSAGES (PHONE_NUMBER, CREATED_AT);
CREATE UNIQUE INDEX IF NOT EXISTS UQ_CONVERSATION_MESSAGES_CHANNEL_EXTERNAL_MESSAGE_ID
    ON CONVERSATION_MESSAGES (CHANNEL, EXTERNAL_MESSAGE_ID);

CREATE TABLE IF NOT EXISTS LEADS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SESSION_ID BIGINT NOT NULL,
    PHONE_NUMBER VARCHAR(32) NOT NULL,
    CUSTOMER_NAME VARCHAR(120),
    TREATMENT_INTEREST VARCHAR(120),
    FIRST_TIME BOOLEAN,
    PREFERRED_TIME VARCHAR(120),
    STATUS VARCHAR(32) NOT NULL,
    SUMMARY TEXT,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT FK_LEADS_SESSION FOREIGN KEY (SESSION_ID) REFERENCES CONVERSATION_SESSIONS (ID),
    CONSTRAINT UQ_LEADS_SESSION_ID UNIQUE (SESSION_ID)
);

CREATE INDEX IF NOT EXISTS IDX_LEADS_PHONE ON LEADS (PHONE_NUMBER);
CREATE INDEX IF NOT EXISTS IDX_LEADS_SESSION ON LEADS (SESSION_ID);
CREATE INDEX IF NOT EXISTS IDX_LEADS_STATUS_UPDATED_AT ON LEADS (STATUS, UPDATED_AT);
