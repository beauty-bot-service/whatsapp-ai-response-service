CREATE TABLE IF NOT EXISTS OUTBOUND_MESSAGES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SESSION_ID BIGINT NOT NULL,
    PHONE_NUMBER VARCHAR(32) NOT NULL,
    CHANNEL VARCHAR(32) NOT NULL,
    CONTENT TEXT NOT NULL,
    STATUS VARCHAR(16) NOT NULL,
    ATTEMPT_COUNT INTEGER NOT NULL,
    LAST_ERROR VARCHAR(1000),
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    SENT_AT TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_OUTBOUND_MESSAGES_STATUS_CREATED_AT ON OUTBOUND_MESSAGES (STATUS, CREATED_AT);
CREATE INDEX IF NOT EXISTS IDX_OUTBOUND_MESSAGES_SESSION ON OUTBOUND_MESSAGES (SESSION_ID);
CREATE INDEX IF NOT EXISTS IDX_OUTBOUND_MESSAGES_PHONE ON OUTBOUND_MESSAGES (PHONE_NUMBER);
