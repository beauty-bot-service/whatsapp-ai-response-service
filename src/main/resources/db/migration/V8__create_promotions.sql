CREATE TABLE IF NOT EXISTS PROMOTIONS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLINIC_ID BIGINT NOT NULL,
    CODE VARCHAR(50) NOT NULL,
    TITLE VARCHAR(120) NOT NULL,
    MESSAGE_BODY TEXT NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    VALID_FROM TIMESTAMP WITH TIME ZONE,
    VALID_UNTIL TIMESTAMP WITH TIME ZONE,
    VERSION BIGINT NOT NULL DEFAULT 0,
    CREATED_BY VARCHAR(120) NOT NULL,
    UPDATED_BY VARCHAR(120) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT UK_PROMOTIONS_CLINIC_CODE UNIQUE (CLINIC_ID, CODE)
);

CREATE INDEX IF NOT EXISTS IDX_PROMOTIONS_CLINIC_STATUS
    ON PROMOTIONS (CLINIC_ID, STATUS);
CREATE INDEX IF NOT EXISTS IDX_PROMOTIONS_VALIDITY
    ON PROMOTIONS (CLINIC_ID, VALID_FROM, VALID_UNTIL);

CREATE TABLE IF NOT EXISTS PROMOTION_ALIASES (
    PROMOTION_ID BIGINT NOT NULL,
    ALIAS VARCHAR(80) NOT NULL,
    CONSTRAINT FK_PROMOTION_ALIASES_PROMOTION
        FOREIGN KEY (PROMOTION_ID) REFERENCES PROMOTIONS (ID) ON DELETE CASCADE,
    CONSTRAINT UK_PROMOTION_ALIASES_PROMOTION_ALIAS UNIQUE (PROMOTION_ID, ALIAS)
);

CREATE INDEX IF NOT EXISTS IDX_PROMOTION_ALIASES_PROMOTION
    ON PROMOTION_ALIASES (PROMOTION_ID);

CREATE TABLE IF NOT EXISTS PROMOTION_EVENTS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROMOTION_ID BIGINT NOT NULL,
    CLINIC_ID BIGINT NOT NULL,
    EVENT_TYPE VARCHAR(30) NOT NULL,
    DESCRIPTION VARCHAR(500),
    CREATED_BY VARCHAR(120) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT FK_PROMOTION_EVENTS_PROMOTION
        FOREIGN KEY (PROMOTION_ID) REFERENCES PROMOTIONS (ID)
);

CREATE INDEX IF NOT EXISTS IDX_PROMOTION_EVENTS_PROMOTION
    ON PROMOTION_EVENTS (PROMOTION_ID, CREATED_AT);
CREATE INDEX IF NOT EXISTS IDX_PROMOTION_EVENTS_CLINIC
    ON PROMOTION_EVENTS (CLINIC_ID, CREATED_AT);
